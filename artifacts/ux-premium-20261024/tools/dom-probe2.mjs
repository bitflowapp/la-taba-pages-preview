import { chromium } from '@playwright/test';
const BASE = 'http://127.0.0.1:8231';
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block' })).newPage();
await p.goto(`${BASE}/?reset=1&demo=1`);
await p.waitForURL(u => !u.searchParams.has('reset'));
await p.waitForSelector('[data-view="home"]'); await p.waitForTimeout(1500);
await p.locator('[data-stories-open]').first().click(); await p.waitForTimeout(900);
const out = {};
out.story = await p.evaluate(() => { const d = document.querySelector('dialog[open], [data-stories-viewer], .story-viewer, [role="dialog"]'); return d ? d.outerHTML.slice(0, 5000) : 'none'; });
out.storyBoxes = await p.evaluate(() => { const d = document.querySelector('dialog[open], [role="dialog"]'); return d ? [...d.querySelectorAll('*')].slice(0, 40).map(e => `${e.tagName}.${typeof e.className==='string'?e.className:''} ${Math.round(e.getBoundingClientRect().top)}/${Math.round(e.getBoundingClientRect().height)}x${Math.round(e.getBoundingClientRect().width)}`) : []; });
await p.keyboard.press('Escape'); await p.waitForTimeout(400);
await p.evaluate(() => { location.hash = '#catalog'; });
await p.waitForSelector('[data-product-grid] [data-add-product]');
await p.locator('[data-product-grid] [data-add-product]').first().click();
await p.waitForTimeout(500);
out.toast = await p.evaluate(() => [...document.querySelectorAll('[role="status"], .toast, [aria-live]')].filter(e => e.textContent.trim()).map(e => e.className + ' :: ' + e.textContent.trim().slice(0, 100)));
await p.evaluate(() => { location.hash = '#cart'; }); await p.waitForTimeout(800);
out.cart = await p.evaluate(() => document.querySelector('[data-view="cart"]')?.outerHTML.replace(/<!--[\s\S]*?-->/g, '').slice(0, 14000));
console.log(JSON.stringify(out, null, 1));
await b.close();
