import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entryPoint = path.join(root, 'scripts', 'supabase-browser-entry.mjs');
const outfile = path.join(root, 'js', 'vendor', 'supabase.js');

await build({
  entryPoints: [entryPoint],
  outfile,
  bundle: true,
  charset: 'utf8',
  format: 'esm',
  legalComments: 'none',
  minify: true,
  platform: 'browser',
  sourcemap: false,
  target: ['es2022'],
  treeShaking: true,
  banner: {
    js: '// Generated by npm run vendor:build from @supabase/supabase-js 2.110.8.',
  },
});

console.log(`Supabase browser bundle created: ${path.relative(root, outfile)}`);
